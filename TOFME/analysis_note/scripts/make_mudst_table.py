#!/usr/bin/env python3
"""Per-p-bin comparison of the two MuDst mixed-event estimates (0-5%).
Inputs: logs/ov_numbers.txt (scripts/make_ov.C), logs/mu_numbers.txt (scripts/make_mu.C).
Output: tables/mudst_cmp.tex.  usage: python3 scripts/make_mudst_table.py <note root>"""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1]); assert (root / 'main.tex').exists()
ov = (root / 'logs/ov_numbers.txt').read_text().splitlines()
mu = (root / 'logs/mu_numbers.txt').read_text().splitlines()
f = lambda pat, s: float(re.search(pat, s).group(1))
rows = []
for cen in ('0-5%', '0-80%'):
    for l in ov:
        m = re.match(r'%s p ([\d.]+)-([\d.]+) \|' % re.escape(cen), l)
        if not m: continue
        a, b = m.group(1), m.group(2)
        e = [x for x in mu if x.startswith('%s p %s-%s PRODB' % (cen, a, b))][0]
        rows.append((cen, a, b,
                     f(r'random/SE % ([\d.]+)', e), f(r'HI SE/ME ([\d.]+)', e), int(f(r'SE HI ([\d.]+)', l)),
                     f(r'random/SE % ([\d.]+)', l), f(r'HI SE/ME ([\d.]+)', l),
                     f(r'pi ([\d.]+)', e), f(r'K ([\d.]+)', e), f(r' p ([\d.]+)$', e),
                     f(r'peaks pi ([\d.]+)', l), f(r' K ([\d.]+) p', l), f(r' K [\d.]+ p ([\d.]+)', l)))
out = ['% generated by scripts/make_mudst_table.py -- do not edit',
       r'\begin{table}[H]\centering\small',
       r'\caption{MuDst random matches per momentum bin. ``Emul.'' = production emulation with partner-track claims',
       r'(Sec.~\ref{sec:muemul}); ``Overlay'' = production makers re-run on the overlaid hits, partner tracks absent',
       r'(Sec.~\ref{sec:muov}). $f$ = ME/SE of all TOF matches (\%); HI = SE/ME for $1.6<m^2<2.8$\,GeV$^2$/$c^4$;',
       r'$N_{\rm HI}$ = SE entries in HI; $\pi$/K/p = ME/SE under the peaks (\%).}',
       r'\label{tab:mudstcmp}',
       r'\begin{tabular}{llrrr|rr|rrr|rrr}\hline',
       r' & & \multicolumn{3}{c|}{} & \multicolumn{2}{c|}{} & \multicolumn{3}{c|}{emul.} & \multicolumn{3}{c}{overlay} \\',
       r'cent. & $p$ (GeV/$c$) & $f_{\rm emul}$ & HI$_{\rm emul}$ & $N_{\rm HI}$ & $f_{\rm ov}$ & HI$_{\rm ov}$ & $\pi$ & K & p & $\pi$ & K & p \\ \hline']
last = None
for r in rows:
    if last and r[0] != last: out.append(r'\hline')
    last = r[0]
    c = r[0].replace('%', r'\%')
    out.append('%s & %s--%s & %.1f & %.2f & %d & %.1f & %.2f & %.1f & %.1f & %.1f & %.1f & %.1f & %.1f \\\\' % ((c,) + r[1:]))
out += [r'\hline\end{tabular}\end{table}']
(root / 'tables/mudst_cmp.tex').write_text('\n'.join(out) + '\n')
print('make_mudst_table done:', len(rows), 'rows')
