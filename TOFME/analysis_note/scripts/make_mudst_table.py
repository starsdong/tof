#!/usr/bin/env python3
"""Per-p-bin comparison of the MuDst mixed-event estimates.
Inputs (logs/): ovtrk_numbers.txt, ov_numbers.txt, ovpool_numbers.txt, ovpooltrk_numbers.txt (scripts/make_ov.C)
and mu_numbers.txt (scripts/make_mu.C). Output: tables/mudst_cmp.tex.
usage: python3 scripts/make_mudst_table.py <note root>"""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1]); assert (root / 'main.tex').exists()
rd = lambda n: (root / 'logs' / n).read_text().splitlines()
ovt, ov, pool, poolt, mu = rd('ovtrk_numbers.txt'), rd('ov_numbers.txt'), rd('ovpool_numbers.txt'), rd('ovpooltrk_numbers.txt'), rd('mu_numbers.txt')
f = lambda pat, s: float(re.search(pat, s).group(1))
def line(lines, cen, a, b, extra=''):
    pre = ('%s p %s-%s %s' % (cen, a, b, extra)).strip() + ' '
    return [x for x in lines if x.startswith(pre)][0]
rows = []
for cen in ('0-5%', '0-80%'):
    for l in ovt:
        m = re.match(r'%s p ([\d.]+)-([\d.]+) \|' % re.escape(cen), l)
        if not m: continue
        a, b = m.group(1), m.group(2)
        e = line(mu, cen, a, b, 'PRODB')
        fr = lambda L: f(r'random/SE % ([\d.]+)', line(L, cen, a, b))
        rows.append((cen, a, b, int(f(r'SE HI ([\d.]+)', l)), f(r'random/SE % ([\d.]+)', l), f(r'HI SE/ME ([\d.]+)', l),
                     f(r'peaks pi ([\d.]+)', l), f(r' K ([\d.]+) p', l), f(r' K [\d.]+ p ([\d.]+)', l),
                     f(r'random/SE % ([\d.]+)', e), f(r'HI SE/ME ([\d.]+)', e), fr(ov), fr(pool), fr(poolt)))
out = ['% generated by scripts/make_mudst_table.py -- do not edit',
       r'\begin{table}[H]\centering\footnotesize\setlength{\tabcolsep}{3.5pt}',
       r'\caption{MuDst random matches per momentum bin. Main result: production makers re-run on the overlay of partner hits and',
       r'partner tracks (Sec.~\ref{sec:muov}). $N_{\rm HI}$ = SE entries for $1.6<m^2<2.8$\,GeV$^2$/$c^4$ (HI); $f$ = ME/SE of all TOF',
       r'matches (\%); HI = SE/ME in HI; $\pi$/K/p = ME/SE under the peaks (\%). Cross-checks: emulation with partner-track claims',
       r'(Sec.~\ref{sec:muemul}), overlay of partner hits only, pool (partner hits only, own hits removed) and pool with partner tracks',
       r'(Sec.~\ref{sec:mupool}).}',
       r'\label{tab:mudstcmp}',
       r'\begin{tabular}{llr|rrrrr|rr|rrr}\hline',
       r' & & & \multicolumn{5}{c|}{overlay + partner tracks} & \multicolumn{2}{c|}{emulation} & \multicolumn{3}{c}{$f$ of other setups} \\',
       r'cent. & $p$ (GeV/$c$) & $N_{\rm HI}$ & $f$ & HI & $\pi$ & K & p & $f$ & HI & hits only & pool & pool+trk \\ \hline']
last = None
for r in rows:
    if last and r[0] != last: out.append(r'\hline')
    last = r[0]
    c = r[0].replace('%', r'\%')
    out.append('%s & %s--%s & %d & %.1f & %.2f & %.1f & %.1f & %.1f & %.1f & %.2f & %.1f & %.1f & %.1f \\\\' % ((c,) + r[1:]))
out += [r'\hline\end{tabular}\end{table}']
(root / 'tables/mudst_cmp.tex').write_text('\n'.join(out) + '\n')
# derived numbers (0-5%, 0.2<p<3) from the summary lines
tot = lambda L, cen: f(r'random/SE % ([\d.]+)', [x for x in L if x.startswith(cen + ' 0.2<p<3')][0])
hi = [r[3] for r in rows if r[0] == '0-5%' and float(r[1]) >= 0.4 and float(r[2]) <= 2.0]
d = ['% generated by scripts/make_mudst_table.py -- do not edit',
     r'\newcommand{\poolTrkRemoved}{%.0f}' % (100 * (1 - tot(poolt, '0-5%') / tot(pool, '0-5%'))),
     r'\newcommand{\ovHitsOnlyFactor}{%.1f}' % (tot(ov, '0-5%') / tot(ovt, '0-5%')),
     r'\newcommand{\ovtNHiMin}{%d}' % min(hi), r'\newcommand{\ovtNHiMax}{%d}' % max(hi)]
(root / 'tables/mudst_derived.tex').write_text('\n'.join(d) + '\n')
print('make_mudst_table done:', len(rows), 'rows')
