#!/usr/bin/env python3
"""Tables and number macros for the large MuDst sample (Sec. sec:big).
Inputs (logs/): mubig_numbers.txt (scripts/make_mu.C), qm2_mubig.txt (scripts/make_qm2.C),
fit_mubig.txt, fit_mubigneg.txt, fit_mubigpos.txt (scripts/make_fit.C).
Outputs: tables/big_m1.tex (macros), tables/big_m1_bins.tex, tables/big_m1_fit.tex, tables/big_m1_ratio.tex.
usage: python3 scripts/make_big_tables.py <note root>"""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1]); assert (root / 'main.tex').exists()
rd = lambda n: (root / 'logs' / n).read_text().splitlines()
mu, qm = rd('mubig_numbers.txt'), rd('qm2_mubig.txt')
f = lambda pat, s: float(re.search(pat, s).group(1))
cents = ('0-5%', '0-80%'); tex = lambda c: c.replace('%', r'\%')
# --- per-bin ME vs SE (PRODB = emulation with partner-track claims) and charge split
bins = []
for c in cents:
    for l in mu:
        m = re.match(r'%s p ([\d.]+)-([\d.]+) PRODB' % re.escape(c), l)
        if not m: continue
        a, b = m.groups()
        q = [x for x in qm if x.startswith('%s p %s-%s ' % (c, a, b))][0]
        bins.append((c, a, b, f(r'random/SE % ([\d.]+)', l), f(r'HI SE/ME ([\d.]+)', l), f(r'max ME/SE ([\d.]+)', l),
                     f(r'pi ([\d.]+)', l), f(r' K ([\d.]+)', l), f(r' p ([\d.]+)$', l),
                     f(r'neg ([\d.]+)', q), f(r'pos ([\d.]+)', q)))
o = ['% generated by scripts/make_big_tables.py -- do not edit',
     r'\begin{table}[H]\centering\small',
     r'\caption{Large sample, method 1 (emulation with partner-track claims): random matches per momentum bin. $f$ = ME/SE of all',
     r'TOF matches (\%); HI = SE/ME for $1.6<m^2<2.8$\,GeV$^2$/$c^4$; max = largest bin-by-bin ME/SE (bins with $\ge20$ SE entries);',
     r'$\pi$/K/p = ME/SE under the peaks (\%); $f^-$, $f^+$ = $f$ for negative and positive tracks (from $q\times m^2$).}',
     r'\label{tab:bigbins}',
     r'\begin{tabular}{llrrrrrrrr}\hline',
     r'cent. & $p$ (GeV/$c$) & $f$ & HI & max & $\pi$ & K & p & $f^-$ & $f^+$ \\ \hline']
last = None
for r in bins:
    if last and r[0] != last: o.append(r'\hline')
    last = r[0]
    o.append('%s & %s--%s & %.2f & %.2f & %.1f & %.2f & %.2f & %.2f & %.2f & %.2f \\\\' % ((tex(r[0]),) + r[1:]))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m1_bins.tex').write_text('\n'.join(o) + '\n')
# --- other centralities (30-40%, 60-80%): f and HI per momentum bin, from the same PRODB log lines
oc = {}
for c in ('30-40%', '60-80%'):
    for l in mu:
        m = re.match(r'%s p ([\d.]+)-([\d.]+) PRODB' % re.escape(c), l)
        if m: oc.setdefault(m.groups(), {})[c] = (f(r'random/SE % ([\d.]+)', l), f(r'HI SE/ME ([\d.]+)', l), f(r' p ([\d.]+)$', l))
hi_fmt = lambda x: '--' if x == 0 else '%.2f' % x
o = ['% generated by scripts/make_big_tables.py -- do not edit',
     r'\begin{table}[H]\centering\small',
     r'\caption{Large sample, method 1, mid-central (30--40\%) and peripheral (60--80\%) events: random matches $f$ (ME/SE of all TOF',
     r'matches, \%), ME/SE under the proton peak (\%) and SE/ME between the p and d peaks (HI, $1.6<m^2<2.8$\,GeV$^2$/$c^4$; -- = no ME',
     r'entries) per momentum bin.}',
     r'\label{tab:bigcent}',
     r'\begin{tabular}{lrrrrrr}\hline',
     r' & \multicolumn{3}{c}{30--40\%} & \multicolumn{3}{c}{60--80\%} \\',
     r'$p$ (GeV/$c$) & $f$ & p & HI & $f$ & p & HI \\ \hline']
for (a_, b_), v in oc.items():
    x, y = v['30-40%'], v['60-80%']
    o.append('%s--%s & %.2f & %.2f & %s & %.2f & %.2f & %s \\\\' % (a_, b_, x[0], x[2], hi_fmt(x[1]), y[0], y[2], hi_fmt(y[1])))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m1_cent.tex').write_text('\n'.join(o) + '\n')
OC = {('Mid', '30-40%'), ('Per', '60-80%')}
oc_macros = {}
for nm, c in OC:
    tot = [l for l in mu if l.startswith(c + ' 0.2<p<3')][0]
    oc_macros['bigFr%s' % nm] = '%.2f' % f(r'prod ([\d.]+) \|', tot)
    oc_macros['bigHi%s' % nm] = '%.1f' % f(r'HI SE/ME ToT [\d.]+ time [\d.]+ prod ([\d.]+)', tot)
    oc_macros['bigHiLow%s' % nm] = '%.1f' % oc[('0.2', '0.4')][c][1]
# --- fits
def rfit(name):
    d = {}
    for l in rd(name):
        if '| SE' not in l: continue
        k = l[:l.index(' |')]
        chi = [float(x) for x in re.search(r'G ([\d.e+]+) G2 ([\d.e+]+) T ([\d.e+]+) T2 ([\d.e+]+)', l).groups()]
        Y = [float(x) for x in re.findall(r'Y ([\d.e+-]+) \+-', l)]
        d[k] = dict(chi=chi, best=re.search(r'best (\w+)', l).group(1), Y=Y, sumY=f(r'sumY/S ([\d.]+)', l))
    summ = {c: [x for x in rd(name) if x.startswith(c + ' summary')][0] for c in cents}
    return d, summ
fa, sa = rfit('fit_mubig.txt'); fn, sn = rfit('fit_mubigneg.txt'); fp, sp = rfit('fit_mubigpos.txt')
o = ['% generated by scripts/make_big_tables.py -- do not edit',
     r'\begin{table}[H]\centering\footnotesize\setlength{\tabcolsep}{4pt}',
     r'\caption{Large sample, method 1, all tracks: Pearson $\chi^2$/ndf of the four line-shape models (G Gaussian, G2 double Gaussian,',
     r'T Student-t, T2 split Student-t), the best model, the yields of the best model and the sum of yields over SE$-$ME.}',
     r'\label{tab:bigfit}',
     r'\begin{tabular}{llrrrrlrrrrr}\hline',
     r'cent. & $p$ (GeV/$c$) & G & G2 & T & T2 & best & $Y_\pi$ & $Y_K$ & $Y_p$ & $Y_d$ & $\sum Y/S$ \\ \hline']
last = None
fmt = lambda x: ('%.0f' % x) if x >= 100 else ('%.1f' % x)
for k, v in fa.items():
    c = k.split(' ')[0]
    if last and c != last: o.append(r'\hline')
    last = c
    p = k.split(' ')[2]
    o.append('%s & %s & %s & %s & %s & %s & %s & %.3g & %.3g & %.3g & %.3g & %.3f \\\\' % (tex(c), p.replace('-', '--'), *[fmt(x) for x in v['chi']], v['best'], *v['Y'], v['sumY']))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m1_fit.tex').write_text('\n'.join(o) + '\n')
# --- ratios from the charge-separated fits
o = ['% generated by scripts/make_big_tables.py -- do not edit',
     r'\begin{table}[H]\centering\small',
     r'\caption{Large sample, method 1, 0--5\%: antiparticle/particle yield ratios from the separate fits of negative and positive tracks',
     r'(best model each), and the closure of the charge-separated fits against the all-track fit, $(Y^-+Y^+)/Y$.}',
     r'\label{tab:bigratio}',
     r'\begin{tabular}{lrrrrrr}\hline',
     r'$p$ (GeV/$c$) & $\pi^-/\pi^+$ & K$^-$/K$^+$ & $\bar{\rm p}$/p & closure $\pi$ & closure K & closure p \\ \hline']
rat = {}
for k, v in fa.items():
    if not k.startswith('0-5%'): continue
    yn, yp, ya = fn[k]['Y'], fp[k]['Y'], v['Y']
    r = [yn[i] / yp[i] if yp[i] > 0 else float('nan') for i in range(3)]
    cl = [(yn[i] + yp[i]) / ya[i] if ya[i] > 0 else float('nan') for i in range(3)]
    rat[k.split(' ')[2]] = (r, cl)
    o.append('%s & %.2f & %.2f & %.3f & %.3f & %.3f & %.3f \\\\' % (k.split(' ')[2].replace('-', '--'), *r, *cl))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m1_ratio.tex').write_text('\n'.join(o) + '\n')
# --- macros
M = dict(oc_macros)
def summ_vals(s):
    best = [int(x) for x in re.search(r'best model G (\d+) G2 (\d+) T (\d+) T2 (\d+) of (\d+)', s).groups()]
    chi = [float(x) for x in re.search(r'mean chi2/ndf G ([\d.]+) G2 ([\d.]+) T ([\d.]+) T2 ([\d.]+)', s).groups()]
    fam = int(re.search(r'Student-t family better in (\d+)', s).group(1))
    return best, chi, fam
for tagq, S in (('', sa), ('Neg', sn), ('Pos', sp)):
    for c, cm in (('0-5%', 'Ci'), ('0-80%', 'All')):
        best, chi, fam = summ_vals(S[c])
        M['bigFit%sTtwoBest%s' % (tagq, cm)] = '%d' % best[3]
        M['bigFit%sNbins%s' % (tagq, cm)] = '%d' % best[4]
        M['bigFit%sTfam%s' % (tagq, cm)] = '%d' % fam
        for nm, x in zip(('G', 'Gtwo', 'T', 'Ttwo'), chi): M['bigFit%sChi%s%s' % (tagq, nm, cm)] = '%.0f' % x
mid = [v for k, v in rat.items() if 0.4 <= float(k.split('-')[0]) and float(k.split('-')[1]) <= 2.5]
for i, nm in enumerate(('Pi', 'K', 'P')):
    vals = [m[0][i] for m in mid]; cls = [m[1][i] for m in mid]
    M['bigRat%sMin' % nm] = ('%.3f' if nm == 'P' else '%.2f') % min(vals); M['bigRat%sMax' % nm] = ('%.3f' if nm == 'P' else '%.2f') % max(vals)
    M['bigClos%sDev' % nm] = '%.1f' % (100 * max(abs(x - 1) for x in cls))
sums = [v['sumY'] for v in fa.values()]
M['bigSumYDev'] = '%.1f' % (100 * max(abs(x - 1) for x in sums))
T2chi = {k: v['chi'][3] for k, v in fa.items() if k.startswith('0-5%')}
M['bigTtwoChiLowP'] = '%.0f' % T2chi['0-5% p 0.2-0.4']
M['bigTtwoChiMidMin'] = '%.0f' % min(T2chi[k] for k in T2chi if k.split(' ')[2] in ('0.4-0.6', '0.6-0.8', '0.8-1'))
M['bigTtwoChiMidMax'] = '%.0f' % max(T2chi[k] for k in T2chi if k.split(' ')[2] in ('0.4-0.6', '0.6-0.8', '0.8-1'))
M['bigTtwoChiHiMin'] = '%.1f' % min(T2chi[k] for k in T2chi if k.split(' ')[2] in ('1-1.2', '1.2-1.5', '1.5-2'))
M['bigTtwoChiHiMax'] = '%.1f' % max(T2chi[k] for k in T2chi if k.split(' ')[2] in ('1-1.2', '1.2-1.5', '1.5-2'))
M['bigTtwoChiTopMin'] = '%.1f' % min(T2chi[k] for k in T2chi if k.split(' ')[2] in ('2-2.5', '2.5-3'))
M['bigTtwoChiTopMax'] = '%.1f' % max(T2chi[k] for k in T2chi if k.split(' ')[2] in ('2-2.5', '2.5-3'))
hi = {r[1] + '-' + r[2]: r[4] for r in bins if r[0] == '0-5%'}
mids = [hi[k] for k in hi if 0.6 <= float(k.split('-')[0]) and float(k.split('-')[1]) <= 2.0]
M['bigHiMidMin'] = '%.2f' % min(mids); M['bigHiMidMax'] = '%.2f' % max(mids)
M['bigHiLow'] = '%.2f' % hi['0.2-0.4']
M['bigHiTopMin'] = '%.1f' % min(hi['2-2.5'], hi['2.5-3']); M['bigHiTopMax'] = '%.1f' % max(hi['2-2.5'], hi['2.5-3'])
o = ['% generated by scripts/make_big_tables.py -- do not edit'] + [r'\newcommand{\%s}{%s}' % (k, v) for k, v in M.items()]
(root / 'tables/big_m1.tex').write_text('\n'.join(o) + '\n')
print('make_big_tables done:', len(bins), 'bin rows,', len(fa), 'fit rows,', len(M), 'macros')
