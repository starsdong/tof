#!/usr/bin/env python3
"""Tables and number macros for method 2 on the large MuDst sample, and the comparison with method 1 (Sec. sec:bigm2).
Inputs (logs/): ovbig_numbers.txt (scripts/make_ov.C, tag big), mubig_numbers.txt (scripts/make_mu.C, tag big),
qm2_ovbig.txt (scripts/make_qm2.C), fit_ovbig{,neg,pos}.txt and fit_mubig.txt (scripts/make_fit.C).
Outputs: tables/big_m2.tex (macros), tables/big_m2_cmp.tex, tables/big_m2_cent.tex, tables/big_m2_fit.tex.
usage: python3 scripts/make_big_m2_tables.py <note root>"""
import re, sys, pathlib
root = pathlib.Path(sys.argv[1]); assert (root / 'main.tex').exists()
rd = lambda n: (root / 'logs' / n).read_text().splitlines()
ov, mu, qm = rd('ovbig_numbers.txt'), rd('mubig_numbers.txt'), rd('qm2_ovbig.txt')
f = lambda pat, s: float(re.search(pat, s).group(1))
tex = lambda c: c.replace('%', r'\%')
M = {}
# --- per-bin comparison, 0-5% and 0-80%
o = ['% generated by scripts/make_big_m2_tables.py -- do not edit',
     r'\begin{table}[H]\centering\small',
     r'\caption{Large sample: method 2 (overlay with partner tracks, production makers re-run) per momentum bin, with method 1 for',
     r'comparison. $f$ = ME/SE of all TOF matches (\%); HI = SE/ME for $1.6<m^2<2.8$\,GeV$^2$/$c^4$; $\pi$/K/p = ME/SE under the peaks',
     r'(\%, method 2); $f^-$, $f^+$ = $f$ of negative and positive tracks (method 2).}',
     r'\label{tab:bigm2bins}',
     r'\begin{tabular}{llrrrrrrrrr}\hline',
     r' & & \multicolumn{2}{c}{$f$} & \multicolumn{2}{c}{HI} & & & & & \\',
     r'cent. & $p$ (GeV/$c$) & m1 & m2 & m1 & m2 & $\pi$ & K & p & $f^-$ & $f^+$ \\ \hline']
last = None
hi2 = {}
for c in ('0-5%', '0-80%'):
    for l in ov:
        m = re.match(r'%s p ([\d.]+)-([\d.]+) \| random' % re.escape(c), l)
        if not m: continue
        a, b = m.groups()
        l1 = [x for x in mu if x.startswith('%s p %s-%s PRODB' % (c, a, b))][0]
        q = [x for x in qm if x.startswith('%s p %s-%s ' % (c, a, b))][0]
        hi2[(c, a + '-' + b)] = f(r'HI SE/ME ([\d.]+)', l)
        if last and c != last: o.append(r'\hline')
        last = c
        o.append('%s & %s--%s & %.2f & %.2f & %.2f & %.2f & %.2f & %.2f & %.2f & %.2f & %.2f \\\\' % (
            tex(c), a, b, f(r'random/SE % ([\d.]+)', l1), f(r'random/SE % ([\d.]+)', l), f(r'HI SE/ME ([\d.]+)', l1), f(r'HI SE/ME ([\d.]+)', l),
            f(r'peaks pi ([\d.]+)', l), f(r' K ([\d.]+)', l), f(r' p ([\d.]+) \|', l), f(r'neg ([\d.]+)', q), f(r'pos ([\d.]+)', q)))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m2_bins.tex').write_text('\n'.join(o) + '\n')
mids = [hi2[('0-5%', k)] for k in ('0.6-0.8', '0.8-1', '1-1.2', '1.2-1.5', '1.5-2')]
M['bigTwoHiMidMin'] = '%.2f' % min(mids); M['bigTwoHiMidMax'] = '%.2f' % max(mids)
M['bigTwoHiLow'] = '%.2f' % hi2[('0-5%', '0.2-0.4')]
# --- centrality summary
o = ['% generated by scripts/make_big_m2_tables.py -- do not edit',
     r'\begin{table}[H]\centering\small',
     r'\caption{Large sample: random matches $f$ (\% of TOF matches, $0.2<p<3$\,GeV/$c$) and SE/ME between the p and d peaks (HI) per',
     r'centrality group, methods 1 and 2.}',
     r'\label{tab:bigm2cent}',
     r'\begin{tabular}{lrrrr}\hline',
     r' & \multicolumn{2}{c}{$f$ (\%)} & \multicolumn{2}{c}{HI} \\',
     r'centrality & m1 & m2 & m1 & m2 \\ \hline']
fr = {}
for c in ('0-5%', '30-40%', '60-80%', '0-80%'):
    l1 = [x for x in mu if x.startswith(c + ' 0.2<p<3')][0]; l2 = [x for x in ov if x.startswith(c + ' 0.2<p<3')][0]
    v = (f(r'prod ([\d.]+) \|', l1), f(r'random/SE % ([\d.]+)', l2), f(r'HI SE/ME ToT [\d.]+ time [\d.]+ prod ([\d.]+)', l1), f(r'HI SE/ME ([\d.]+)', l2))
    fr[c] = v
    o.append('%s & %.2f & %.2f & %.2f & %.2f \\\\' % ((tex(c),) + v))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m2_cent.tex').write_text('\n'.join(o) + '\n')
M['bigTwoOneFrDev'] = '%.0f' % (100 * max(abs(v[1] / v[0] - 1) for v in fr.values()))
# --- fits
def rfit(name):
    d = {}
    for l in rd(name):
        if '| SE' not in l: continue
        k = l[:l.index(' |')]
        d[k] = dict(chi=[float(x) for x in re.search(r'G ([\d.e+]+) G2 ([\d.e+]+) T ([\d.e+]+) T2 ([\d.e+]+)', l).groups()],
                    best=re.search(r'best (\w+)', l).group(1), Y=[float(x) for x in re.findall(r'Y ([\d.e+-]+) \+-', l)],
                    sumY=f(r'sumY/S ([\d.]+)', l))
    summ = {c: [x for x in rd(name) if x.startswith(c + ' summary')][0] for c in ('0-5%', '0-80%')}
    return d, summ
fa, sa = rfit('fit_ovbig.txt'); fn, sn = rfit('fit_ovbigneg.txt'); fp, sp = rfit('fit_ovbigpos.txt'); f1, _ = rfit('fit_mubig.txt')
fmt = lambda x: ('%.0f' % x) if x >= 100 else ('%.1f' % x)
o = ['% generated by scripts/make_big_m2_tables.py -- do not edit',
     r'\begin{table}[H]\centering\footnotesize\setlength{\tabcolsep}{4pt}',
     r'\caption{Large sample, method 2, all tracks: Pearson $\chi^2$/ndf of the four line-shape models, the best model, and the ratio of',
     r'the method-2 to method-1 yields of the best models ($Y_2/Y_1$).}',
     r'\label{tab:bigm2fit}',
     r'\begin{tabular}{llrrrrlrrr}\hline',
     r'cent. & $p$ (GeV/$c$) & G & G2 & T & T2 & best & $Y_2/Y_1$ $\pi$ & K & p \\ \hline']
last = None
agree = []
for k, v in fa.items():
    c, pp = k.split(' ')[0], k.split(' ')[2]
    if last and c != last: o.append(r'\hline')
    last = c
    r = [v['Y'][i] / f1[k]['Y'][i] for i in range(3)]
    if 0.4 <= float(pp.split('-')[0]) and float(pp.split('-')[1]) <= 2.0: agree += r
    o.append('%s & %s & %s & %s & %s & %s & %s & %.3f & %.3f & %.3f \\\\' % (tex(c), pp.replace('-', '--'), *[fmt(x) for x in v['chi']], v['best'], *r))
o.append(r'\hline\end{tabular}\end{table}')
(root / 'tables/big_m2_fit.tex').write_text('\n'.join(o) + '\n')
M['bigTwoYieldAgree'] = '%.1f' % (100 * max(abs(x - 1) for x in agree))
lowp = fa['0-5% p 0.2-0.4']['Y'][2] / f1['0-5% p 0.2-0.4']['Y'][2]
M['bigTwoYieldLowP'] = '%.0f' % (100 * (lowp - 1))
for tagq, S in (('', sa), ('Neg', sn), ('Pos', sp)):
    for c, cm in (('0-5%', 'Ci'), ('0-80%', 'All')):
        s = S[c]
        best = [int(x) for x in re.search(r'best model G (\d+) G2 (\d+) T (\d+) T2 (\d+) of (\d+)', s).groups()]
        chi = [float(x) for x in re.search(r'mean chi2/ndf G ([\d.]+) G2 ([\d.]+) T ([\d.]+) T2 ([\d.]+)', s).groups()]
        M['bigTwoFit%sTtwoBest%s' % (tagq, cm)] = '%d' % best[3]
        M['bigTwoFit%sTfam%s' % (tagq, cm)] = re.search(r'Student-t family better in (\d+)', s).group(1)
        for nm, x in zip(('Gtwo', 'T', 'Ttwo'), chi[1:]): M['bigTwoFit%sChi%s%s' % (tagq, nm, cm)] = '%.0f' % x
rat = [[fn[k]['Y'][i] / fp[k]['Y'][i] for i in range(3)] for k in fa if k.startswith('0-5%')
       and 0.4 <= float(k.split(' ')[2].split('-')[0]) and float(k.split(' ')[2].split('-')[1]) <= 2.5]
for i, nm in enumerate(('Pi', 'K', 'P')):
    vals = [r[i] for r in rat]; fm = '%.3f' if nm == 'P' else '%.2f'
    M['bigTwoRat%sMin' % nm] = fm % min(vals); M['bigTwoRat%sMax' % nm] = fm % max(vals)
M['bigTwoSumYDev'] = '%.1f' % (100 * max(abs(v['sumY'] - 1) for v in fa.values()))
o = ['% generated by scripts/make_big_m2_tables.py -- do not edit'] + [r'\newcommand{\%s}{%s}' % (k, v) for k, v in M.items()]
(root / 'tables/big_m2.tex').write_text('\n'.join(o) + '\n')
print('make_big_m2_tables done:', len(M), 'macros')
