#!/usr/bin/env python3
"""Extract run-level provenance numbers from the root4star log -> tables/runinfo.tex, logs/runinfo.txt.
usage: parse_log.py <note_root>"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1]).resolve()
assert (root / "main.tex").exists(), f"not a note root: {root}"
log = (root / "logs/qa_test_10k.log").read_text(errors="replace")
lst = (root / "data/test.list").read_text().split()
prov = (root / "logs/provenance.txt").read_text()

vals = {}
m = re.search(r"runTofMEQA: (\d+) events in chain, processing (\d+)", log)
vals["nChainEvents"], vals["nProcEvents"] = m.group(1), m.group(2)
m = re.search(r"StChain::bfcChain\s+Ast =\s*([\d.]+)\s+Cpu =\s*([\d.]+)", log)
vals["wallSec"], vals["cpuSec"] = f"{float(m.group(1)):.0f}", f"{float(m.group(2)):.1f}"
m = re.search(r"StPicoDstMaker::picoDst\s+Ast =\s*[\d.]+\(\s*([\d.]+)%\)", log)
vals["picoWallPct"] = m.group(1)
m = re.search(r"Start at Date : (.+)", log)
vals["runDate"] = m.group(1).strip()
vals["nFilesRead"] = re.search(r"Total (\d+) files have been read in", log).group(1)
vals["inputFile"] = lst[0].split("/")[-1]
vals["inputUrl"] = lst[0]
vals["rootVersion"] = re.search(r"^(\d+\.\d+/\d+)$", prov, re.M).group(1)
vals["gccVersion"] = re.search(r"gcc \(GCC\) (\S+)", prov).group(1)
vals["containerImage"] = re.search(r"-> (\S+\.sif)", prov).group(1)
vals["hostOS"] = re.search(r"os: (.+?)\n", prov).group(1)
vals["containerOS"] = re.search(r"container os: (.+?)\n", prov).group(1)

with open(root / "logs/runinfo.txt", "w") as f:
    for k, v in vals.items():
        f.write(f"{k} = {v}\n")
with open(root / "tables/runinfo.tex", "w") as f:
    f.write("% generated by scripts/parse_log.py -- do not edit\n")
    for k, v in vals.items():
        if k in ("inputUrl", "containerImage", "inputFile"):
            f.write(f"\\newcommand{{\\{k}}}{{\\nolinkurl{{{v}}}}}\n")
        else:
            f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print("wrote tables/runinfo.tex:", vals)
# geometry file counts
gv = {"geoNFitted": 0, "geoNRot": 0, "geoNNone": 0}
for line in (root / "data/btof_geom_test.txt").read_text().splitlines():
    if line.startswith("#") or not line.strip():
        continue
    fl = int(line.split()[3])
    gv["geoNFitted" if fl == 1 else ("geoNRot" if fl == 2 else "geoNNone")] += 1
mk = re.search(r"\|U\| mean ([\d.]+)", (root / "logs/makeGeom_test.log").read_text())
gv["geoUmag"] = mk.group(1)
with open(root / "tables/geominfo.tex", "w") as f:
    f.write("% generated by scripts/parse_log.py from data/btof_geom_test.txt, logs/makeGeom_test.log\n")
    for k, v in gv.items():
        f.write(f"\\newcommand{{\\{k}Test}}{{{v}}}\n")
print("geometry:", gv)
